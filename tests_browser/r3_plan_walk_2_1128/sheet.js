const { chromium } = require('playwright')
;(async () => { const browser = await chromium.launch(); const page = await (await browser.newContext({ viewport: { width: 1366, height: 900 } })).newPage()
  await page.goto('http://127.0.0.1:4173/strategy/builder?strategy=2'); await page.waitForTimeout(7000)
  await page.getByRole('button', { name: 'Edit plan' }).click(); await page.waitForTimeout(2500)
  const d = page.getByRole('dialog').first()
  console.log((await d.innerText()).replace(/\s+/g, ' ').slice(0, 2500))
  console.log('CONTROLS', await d.locator('input,select,button').evaluateAll(x => x.map(e => `${e.tagName}:${e.type||''}:${(e.getAttribute('aria-label')||e.name||e.id||e.innerText||'').trim().slice(0,40)}${e.type==='checkbox'?(e.checked?'[x]':'[ ]'):''}`).join(' | ')))
  await page.screenshot({ path: '/tmp/claude-0/sp/sheet.jpg', type: 'jpeg', quality: 50 })
  await browser.close() })()
