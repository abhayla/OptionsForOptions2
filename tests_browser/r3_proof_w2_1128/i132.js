// Lane W2 I-132 (page half): move a leg that has a stop (scenario PATH-01 stores orders): the new leg shows the stop line / the hedged sentence
const { launch, shot, body, MAIN } = require('./common')
;(async () => {
  const { browser, page } = await launch()
  const posts = []; page.on('response', async (r) => { if (r.request().method() === 'POST' && /\/orders$/.test(r.url())) posts.push(r.status() + ' ' + (await r.text().catch(() => '')).match(/"cancelled_stops":\[[^\]]*\]/)?.[0]) })
  await page.goto(MAIN + '/strategy/builder?strategy=1'); await page.waitForTimeout(9000)
  console.log('strike steppers:', await page.getByRole('button', { name: /^\+$/ }).count(), '| rows:', await page.locator('[data-testid^=leg-row]').count())
  // move the sold 23150 PE one strike up
  await page.getByRole('button', { name: 'Next strike' }).nth(1).click().catch(e => console.log('plus click err', String(e).slice(0, 120)))
  await page.waitForTimeout(3000)
  const t = await body(page)
  console.log('pending:', (t.match(/\d+ pending changes?/) || ['-'])[0], '| stop sentence:', (t.match(/[^|]*stop on[^|]*/gi) || ['<none>']).join(' ;; ').slice(0, 300))
  await shot(page, 'i132-1-staged')
  await page.getByRole('button', { name: /Review/ }).first().click({ timeout: 8000 }); await page.waitForTimeout(12000)
  console.log('REVIEW:', (await page.getByRole('dialog').first().innerText().catch(() => '<no dialog>')).replace(/\s+/g, ' ').slice(0, 900))
  await shot(page, 'i132-2-review')
  const conf = page.getByRole('button', { name: 'Confirm' }).last()
  console.log('Confirm enabled:', await conf.isEnabled().catch(() => 'n/a'))
  await conf.click({ timeout: 4000 }).catch(e => console.log('confirm err', String(e).slice(0, 100))); await page.waitForTimeout(8000)
  const t2 = await body(page)
  console.log('POST replies:', JSON.stringify(posts))
  console.log('AFTER:', (t2.match(/[^|]*(stop on|was removed|stop-offer|set a new one|may have been cancelled)[^|]*/gi) || ['<no stop line>']).join(' ;; ').slice(0, 500))
  await shot(page, 'i132-3-after'); await browser.close()
})()
