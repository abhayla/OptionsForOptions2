// Lane TG item 4: TC-2 chain, TC-3 notification settings, W-18 rename Esc, TC-5/W-29(57) closed trade, completed page
const { launch, shot, body, MAIN } = require('./common')
;(async () => {
  const { browser, page } = await launch()
  const lines = async (re, n = 6) => (await body(page)).split(' | ').filter(l => re.test(l)).slice(0, n).map(l => l.slice(0, 200))
  await page.goto(MAIN + '/market/option-chain'); await page.waitForTimeout(8000)
  await page.getByRole('button', { name: 'SENSEX' }).click().catch(() => {}); await page.waitForTimeout(5000)
  console.log('TC-2 SENSEX:', JSON.stringify(await lines(/Market closed|catalogue|No strikes|unavailable|Waiting|Option chain unavailable|not in the|SENSEX/i, 8)))
  await shot(page, 'tc2-sensex')
  await page.getByRole('button', { name: 'NIFTY', exact: true }).click().catch(() => {}); await page.waitForTimeout(3000)
  const far = page.getByRole('button', { name: /14 Dec/ }); if (await far.count()) { await far.first().click(); await page.waitForTimeout(4000) }
  console.log('TC-2 NIFTY 14 Dec:', JSON.stringify(await lines(/Market closed|catalogue|No strikes|unavailable|not in the/i, 6)), '| blank cell title:', await page.locator('td[title]').first().getAttribute('title').catch(() => 'none'), '| status words Stale/Delayed/Unhealthy/reconnecting:', /Stale|Delayed|Unhealthy|reconnecting/i.test(await body(page)))
  await page.goto(MAIN + '/alerts/active'); await page.waitForTimeout(5000)
  await page.getByText(/notification/i).first().click().catch(() => {}); await page.waitForTimeout(2000)
  console.log('TC-3:', JSON.stringify(await lines(/notification|channel|side closed|Add the legs/i, 5)))
  await shot(page, 'tc3-notifications')
  await page.goto(MAIN + '/strategies/my-strategies'); await page.waitForTimeout(6000)
  await page.getByRole('button', { name: /^Rename$/ }).first().click(); await page.waitForTimeout(500)
  await page.keyboard.type('zz'); await page.waitForTimeout(300)
  const typed = await page.locator('input:focus').inputValue().catch(() => '<no focus>')
  await page.keyboard.press('Escape'); await page.waitForTimeout(800)
  console.log('W-18 rename: text went in =', typed, '| input still open after Esc:', await page.locator('input:focus').count())
  await page.goto(MAIN + '/strategy/builder?strategy=4'); await page.waitForTimeout(7000)
  console.log('W-29(57) #4:', JSON.stringify(await lines(/This trade is closed|Plan:|Closed|Plan watch|Add a leg|Add\/Edit/i, 6)))
  await shot(page, 'w29-closed')
  await page.goto(MAIN + '/strategies/completed-strategies'); await page.waitForTimeout(6000)
  console.log('TC-5 completed page:', JSON.stringify(await lines(/closed|Charges|Net after|Final P&L|Adjust/i, 6)))
  await shot(page, 'tc5-completed')
  await page.goto(MAIN + '/alerts/history'); await page.waitForTimeout(5000)
  console.log('W-28(3) History:', JSON.stringify(await lines(/Answered alerts|Stops and expiry|No answered|No stops/i, 6)))
  await browser.close()
})()
