const { launch, shot, body, MAIN } = require('./common')
;(async () => {
  const { browser, page } = await launch()
  await page.goto(MAIN + '/strategy/builder?strategy=1'); await page.waitForTimeout(7000)
  const dlg = async () => (await page.getByRole('dialog').first().innerText().catch(() => '<none>')).replace(/\s+/g, ' ')
  const vals = async () => page.getByRole('dialog').first().locator('input:not([type=time]):not([type=date])').evaluateAll(x => x.map(e => e.value).join(' / '))
  await page.getByRole('button', { name: 'Edit plan' }).click(); await page.waitForTimeout(2000)
  console.log('open: target%/targetRs/stop%/stopRs/maxadj =', await vals())
  const inputs = page.getByRole('dialog').first().locator('input:not([type=time]):not([type=date])')
  await inputs.nth(3).fill('100'); await page.getByRole('button', { name: 'Save plan' }).click(); await page.waitForTimeout(5000)
  console.log('after Save stop 100: dialog open?', /Save plan/.test(await dlg()), '| values', await vals())
  const m = (await dlg()).match(/(Saved|Not confirmed|could not|Prices could not|refus)[^.]*\./g); console.log('save sentences:', m)
  await shot(page, 'w01-1-save')
  if (!/Save plan/.test(await dlg())) { await page.getByRole('button', { name: 'Edit plan' }).click(); await page.waitForTimeout(2000) }
  console.log('values before reset', await vals())
  await page.getByRole('button', { name: 'Reset to playbook' }).first().click(); await page.waitForTimeout(1500); await page.getByRole('button', { name: 'Reset to playbook' }).last().click(); await page.waitForTimeout(4000)
  const d = await dlg(); console.log('after Reset values', await vals()); console.log('RESET TEXT:', (d.match(/Put back[^|]*?(?=Close|Save plan|$)/) || d.match(/Nothing differed[^.]*\./) || ['<neither>'])[0].slice(0, 500))
  console.log('full tail:', d.slice(-500))
  await shot(page, 'w01-2-reset')
  await browser.close()
})()
