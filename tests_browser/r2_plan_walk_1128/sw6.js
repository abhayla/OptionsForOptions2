const { launch, shot, body, MAIN } = require('./common')
;(async () => {
  const { browser, page } = await launch()
  const posts = []; page.on('request', (r) => { if (r.method() === 'POST') posts.push(r.url().replace(/^https?:\/\/[^/]+/, '')) })
  await page.goto(MAIN + '/strategy/builder'); await page.waitForTimeout(5000)
  await page.getByRole('button', { name: 'Ready-made' }).click().catch(() => {}); await page.waitForTimeout(1000)
  await page.getByRole('button', { name: 'Bull Put Spread' }).first().click(); await page.waitForTimeout(5000)
  console.log('buttons:', (await page.getByRole('button').allInnerTexts()).filter(x => /Paper|Add|Confirm|Review/i.test(x)).join(' | '))
  const add = page.getByRole('button', { name: /Add to Paper/ }).first()
  console.log('Add to Paper count', await add.count(), 'disabled', await add.isDisabled().catch(() => 'n/a'))
  await shot(page, 'sw6-1-builder-draft')
  await add.click(); await page.waitForTimeout(2000); await page.getByRole('dialog').first().locator('input').first().fill('TG sw6 draft'); await page.getByRole('button', { name: 'Save' }).last().click(); await page.waitForTimeout(4000)
  const d = (await page.getByRole('dialog').first().innerText().catch(() => '<no dialog>')).replace(/\s+/g, ' ')
  console.log('DIALOG:', d.slice(0, 900))
  const conf = page.getByRole('button', { name: 'Confirm' }).last()
  console.log('Confirm disabled:', await conf.isDisabled().catch(() => 'n/a'))
  await shot(page, 'sw6-2-add-dialog')
  console.log('tick box present:', await page.getByText(/prices are not live/i).count())
  console.log('POSTs so far:', posts.join(' ; '))
  await browser.close()
})()
