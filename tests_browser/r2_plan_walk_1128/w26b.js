const { launch, shot, body, MAIN } = require('./common')
;(async () => {
  const { browser, page } = await launch()
  await page.goto(MAIN + '/strategy/builder?strategy=1'); await page.waitForTimeout(7000)
  const pend = async () => ((await body(page)).match(/\d+ pending changes?/g) || []).join(',')
  console.log('case B before: pending', await pend())
  await page.getByRole('button', { name: 'Exit all' }).click(); await page.waitForTimeout(2500)
  const d = page.getByRole('dialog').first()
  console.log('Confirm disabled:', await page.getByRole('button', { name: 'Confirm' }).last().isDisabled())
  console.log('DIALOG B has discard sentence:', /will be discarded/.test(await d.innerText()))
  await shot(page, 'w26-b1-dialog')
  await page.getByRole('button', { name: 'Cancel' }).last().click(); await page.waitForTimeout(1500)
  const t = await body(page)
  console.log('after Cancel: pending', await pend(), '| staged line:', (t.match(/Exiting these legs[^|]*/) || ['none'])[0], '| Discard offered:', /Discard/.test(t))
  await shot(page, 'w26-b2-after-cancel')
  await browser.close()
})()
