const { launch, shot, body, MAIN } = require('./common')
;(async () => {
  const { browser, page } = await launch()
  const posts = []; page.on('request', (r) => { if (r.method() !== 'GET') posts.push(r.method() + ' ' + r.url().replace(/^https?:\/\/[^/]+/, '')) })
  await page.goto(MAIN + '/strategy/builder?strategy=1'); await page.waitForTimeout(7000)
  const lots = async () => (await page.getByTestId('leg-lots').allInnerTexts()).join(',')
  const pend = async () => ((await body(page)).match(/\d+ pending changes?/g) || []).join(',')
  console.log('before: lots', await lots(), 'pending', await pend())
  // the leg row's lots is a span; the only lots control on a running trade is the Multiplier (all legs) or the strike-edit row
  await page.getByTestId('multiplier').selectOption('2').catch(e => console.log('mult err', e.message.slice(0, 80)))
  await page.waitForTimeout(2000)
  console.log('after multiplier=2: lots', await lots(), 'pending', await pend()); await shot(page, 'w26-a1-raised')
  await page.getByRole('button', { name: 'Exit all' }).click(); await page.waitForTimeout(2500)
  const d = page.getByRole('dialog').first()
  console.log('DIALOG A:', (await d.innerText().catch(() => '<no role=dialog>')).replace(/\s+/g, ' ').slice(0, 1000))
  await shot(page, 'w26-a2-dialog')
  await page.getByRole('button', { name: 'Cancel' }).last().click(); await page.waitForTimeout(1500)
  const t = await body(page)
  console.log('after Cancel: lots', await lots(), 'pending', await pend(), 'multiplier', await page.getByTestId('multiplier').inputValue(), 'staged-exit line', /Exiting these legs/.test(t))
  await shot(page, 'w26-a3-cancelled')
  console.log('non-GET:', posts.join(' ; '))
  await browser.close()
})()
