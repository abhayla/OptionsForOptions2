// Lane TG coordinator walk: Exit with paused prices and the market closed, FJ build 1ad973435 (ADR-330 (60))
const { launch, shot, body, MAIN } = require('./common')
;(async () => {
  const { browser, page } = await launch()
  const posts = []; page.on('request', (r) => { if (r.method() === 'POST') posts.push(r.url().replace(/^https?:\/\/[^/]+/, '')) })
  await page.goto(MAIN + '/positions/current-positions?tab=paper&strategy=1'); await page.waitForTimeout(10000)
  console.log('paused sentence on page:', /Paper P&L paused - prices not live/.test(await body(page)))
  await page.locator('[data-testid^=exit-selected-1]').first().scrollIntoViewIfNeeded().catch(() => {})
  const cbs = page.locator('input[type=checkbox]'); console.log('checkboxes', await cbs.count())
  // tick the first leg of strategy 1's card (they follow the card header)
  for (let i = 0; i < await cbs.count(); i++) { const al = await cbs.nth(i).getAttribute('aria-label'); if (al && /24000 PE|24100 PE|24300 CE|24400 CE/.test(al)) { await cbs.nth(i).check(); console.log('ticked', al); break } }
  await page.waitForTimeout(1200)
  const ex = page.locator('[data-testid=exit-selected-1]')
  console.log('Positions Exit button:', await ex.innerText().catch(() => 'n/a'), '| disabled:', await ex.isDisabled().catch(() => 'n/a'))
  await ex.click({ timeout: 4000 }).catch(e => console.log('click blocked:', e.message.split('\n')[0].slice(0, 80)))
  await page.waitForTimeout(3500)
  const dlg = await page.getByRole('dialog').first().innerText({ timeout: 2000 }).then(x => x.replace(/\s+/g, ' ')).catch(() => '<no dialog>')
  console.log('POSITIONS DIALOG:', dlg.slice(0, 700), '| Confirm disabled:', await page.getByRole('button', { name: 'Confirm' }).last().isDisabled().catch(() => 'n/a'))
  await shot(page, 'fj-exit-positions')
  await page.keyboard.press('Escape')
  await page.goto(MAIN + '/strategy/builder?strategy=1'); await page.waitForTimeout(8000)
  await page.getByRole('button', { name: /^Exit$/ }).first().click({ timeout: 4000 }).catch(e => console.log('builder click blocked'))
  await page.waitForTimeout(3000)
  const d2 = await page.getByRole('dialog').first().innerText({ timeout: 2000 }).then(x => x.replace(/\s+/g, ' ')).catch(() => '<no dialog>')
  console.log('BUILDER DIALOG:', d2.slice(0, 700), '| Confirm disabled:', await page.getByRole('button', { name: 'Confirm' }).last().isDisabled().catch(() => 'n/a'))
  await shot(page, 'fj-exit-builder')
  console.log('POSTs sent:', posts.length)
  await browser.close()
})()
