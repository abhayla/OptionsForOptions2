// I-41 (builder money figures, table total, steps) and I-79 (Greeks tab). One screenshot per step; exact texts printed.
const { launch, shot, text, MAIN } = require('./common')
;(async () => {
  const { browser, ctx } = await launch(); const page = await ctx.newPage()
  const errs = []; page.on('pageerror', e => errs.push('pageerror ' + e.message.slice(0, 150)))
  page.on('console', m => m.type() === 'error' && errs.push('console ' + m.text().slice(0, 150)))
  await page.goto(MAIN + '/strategy/builder?strategy=1'); await page.waitForTimeout(5000)
  const T = async (id) => console.log(`  [${id}]`, await text(page, `[data-testid=${id}]`))
  console.log('STEP 1 left book'); for (const id of ['book-total-label', 'book-total', 'book-charges-label', 'book-charges', 'book-charges-close-label', 'book-charges-close', 'book-read-at', 'paper-pending-count']) await T(id)
  await shot(page, 'i41-01-book-strip')
  console.log('STEP 2 net table rows'); console.log((await page.locator('[data-testid=net-row]').allInnerTexts()).map(s => s.replace(/\s+/g, ' ')).join('\n'))
  console.log('STEP 3 tiles'); for (const id of ['summary-block-outcome', 'max-profit-basis', 'max-profit', 'max-loss-basis', 'max-loss', 'breakevens', 'profit-left', 'loss-left']) await T(id)
  await shot(page, 'i41-02-tiles')
  console.log('STEP 4 P&L tab, table'); await page.click('[data-testid=tab-pnl]'); await page.waitForTimeout(1500)
  await page.click('[data-testid=tab-table]').catch(() => {}); await page.waitForTimeout(800)
  for (const id of ['total-line', 'pnl-charges-paid', 'pnl-charges-close']) await T(id)
  await shot(page, 'i41-03-pnl-table-compact')
  console.log('STEP 5 full table'); await page.click('[data-testid=full-table-switch]').catch(e => console.log('no switch', e.message.slice(0, 80))); await page.waitForTimeout(800)
  await T('total-line'); await shot(page, 'i41-04-pnl-table-full')
  console.log('STEP 6 add booked switch'); const sw = page.locator('[data-testid=add-booked-switch]').first()
  console.log('  switch count', await sw.count())
  if (await sw.count()) { await T('add-booked-switch'); await sw.click().catch(e => console.log('  click fail', e.message.slice(0, 80))); await page.waitForTimeout(1000); await T('total-line'); await T('max-profit'); await T('max-loss'); await shot(page, 'i41-05-add-booked-on') }
  console.log('STEP 7 I-79 Greeks tab'); await page.click('[data-testid=tab-greeks]'); await page.waitForTimeout(1500)
  console.log('  panel-greeks:', (await text(page, '[data-testid=panel-greeks]')).slice(0, 900))
  console.log('  red error boxes:', await page.locator('[role=alert], [data-testid*=error]').count(), (await page.locator('[role=alert]').allInnerTexts()).join(' | ').slice(0, 300))
  await shot(page, 'i79-01-greeks-tab')
  console.log('ERRS', errs); await browser.close()
})()
