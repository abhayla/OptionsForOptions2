// I-93: Stops panel at 1280x800: form and list side by side; press Save; read the scroll position.
const { launch, shot, text, MAIN } = require('./common')
;(async () => {
  const { browser, ctx } = await launch({ width: 1280, height: 800 }); const page = await ctx.newPage()
  page.on('response', r => { if (/trigger/.test(r.url())) console.log('  api', r.status(), r.request().method(), r.url().replace(MAIN, '')) })
  await page.goto(MAIN + '/positions/current-positions'); await page.waitForTimeout(4000)
  console.log('stops-open buttons:', await page.locator('[data-testid^=stops-open-]').evaluateAll(e => e.map(x => x.dataset.testid + ' "' + x.textContent.trim() + '"')))
  await page.locator('[data-testid^=stops-open-]').first().click(); await page.waitForTimeout(1500)
  const box = async (id) => page.locator(`[data-testid=${id}]`).first().boundingBox()
  const f = await box('stops-form'), l = await box('stops-list'); console.log('form box', f, 'list box', l)
  console.log('side by side:', f && l && l.x > f.x + f.width - 2 && Math.abs(l.y - f.y) < 40)
  await shot(page, 'i93-01-stops-side-by-side')
  const sy = () => page.evaluate(() => ({ win: window.scrollY, main: [...document.querySelectorAll('*')].filter(e => e.scrollTop > 0).map(e => (e.dataset.testid || e.tagName) + ':' + e.scrollTop) }))
  await page.locator('[data-testid=paper-stops]').scrollIntoViewIfNeeded(); await page.waitForTimeout(300)
  console.log('scroll before Save', JSON.stringify(await sy()))
  const pb = await box('paper-stops'); console.log('paper-stops box (viewport)', pb)
  await page.fill('[data-testid=ce-above]', '24000'); await page.click('[data-testid=ce-save]'); await page.waitForTimeout(1500)
  console.log('scroll after Save ', JSON.stringify(await sy())); console.log('paper-stops box after', await box('paper-stops'))
  console.log('status:', await text(page, '[data-testid=stops-status-slot]'), '| list:', (await text(page, '[data-testid=triggers]')).slice(0, 300))
  await shot(page, 'i93-02-after-save')
  await browser.close()
})()
